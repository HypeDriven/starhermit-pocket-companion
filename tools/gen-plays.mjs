// Writes the native play scripts (tests/native/*.play) from the rules: each
// session is simulated with the content validator's greedy carer (the lowest
// need's best legal action, decorations first when the goals want them), and
// every move becomes a key press (desktop) or a finger tap on the action tray
// (phone, landscape), so the scripts play the real UI to the results screen.
// The rules are deterministic per stage seed, so the scripts replay exactly.
// Run after changing rules or content: `npm run plays`.
import { writeFileSync } from 'node:fs';
import * as rules from '../src/rules.js';
import * as content from '../src/content.js';
import { Session } from '../src/session.js';

const out = (name, lines) => writeFileSync(new URL(`../tests/native/${name}.play`, import.meta.url), lines.join('\n') + '\n');
const WANT = { hunger: ['feed', 'snack'], hygiene: ['wash'], fun: ['play', 'toss', 'sing', 'pet'], energy: ['rest'] };
const LABEL = (id) => rules.ACTIONS[id].label;
const KEY = (slot) => `Digit${(slot + 1) % 10}`;

/** content.js greedyPick: decorations while the goals want them, else the lowest need's best legal action. */
function greedy(state) {
  const legal = rules.legalActions(state).filter((a) => a.legal && a.kind !== 'pass');
  const wantsDecor = (state.goals.decor && state.decorPlaced.length < state.goals.decor) ||
    (state.goals.discoveries && state.discovered.length < state.goals.discoveries);
  if (wantsDecor && legal.some((a) => a.id === 'decorate')) {
    const item = state.allowedDecor.find((i) => !state.decorPlaced.includes(i));
    if (item) return { type: 'decorate', item };
  }
  const sorted = [...rules.NEEDS].sort((a, b) => state.needs[a] - state.needs[b]);
  for (const need of sorted) for (const id of WANT[need]) if (legal.some((a) => a.id === id)) return { type: id };
  if (legal.length) return { type: [...legal].sort((a, b) => a.ticks - b.ticks)[0].id };
  return { type: 'wait' };
}

/** Plays a config to its end; returns the moves. */
function plan(cfg) {
  const s = new Session(cfg, { mode: 'journey', undo: false, ranked: false, now: 1 });
  const moves = [];
  for (let i = 0; !s.terminal && i < 2000; i++) {
    const m = greedy(s.state);
    const r = s.act(m.type, m.item ? { item: m.item } : {});
    if (!r.ok) throw new Error(`${cfg.id}: illegal ${m.type}`);
    moves.push(m);
  }
  if (s.state.status !== 'complete') throw new Error(`${cfg.id}: ended ${s.state.status}`);
  return { moves, state: s.state };
}
const decorName = (id) => content.DECOR_ITEMS.find((d) => d.id === id).name;

/** One move: a key for its tray slot, or a finger on its tray button (decorations through the drawer). */
function moveLines(cfg, m, how) {
  const slot = cfg.allowedActions.indexOf(m.type);
  if (m.type === 'decorate') {
    return [
      how === 'key' ? `key ${KEY(slot)} 1` : `${how} =Decorate`,
      'until 60 Decorate the room', 'frames 5',
      `${how} ${decorName(m.item)}`, 'frames 5', `${how} =Done`, 'frames 5',
    ];
  }
  return how === 'key' ? [`key ${KEY(slot)} 1`, 'frames 2'] : [`${how} =${LABEL(m.type)}`, 'frames 3'];
}
function session(cfg, how, label) {
  const { moves, state } = plan(cfg);
  const lines = [`# ${label}: ${moves.length} moves, complete at tick ${state.tick} (${state.score.care} care, bond points ${state.bondPoints})`];
  lines.push('until 300 Objective', 'frames 30', `save ${label}-room`);
  moves.forEach((m, i) => {
    lines.push(...moveLines(cfg, m, how));
    if (i === 0) lines.push('frames 10', `save ${label}-play`);
  });
  lines.push('until 300 Results', 'expect Session complete', 'frames 10');
  return lines;
}

// --- Journey 1-3 on a desktop by keys --------------------------------------------------------
{
  const L = ['# Generated by tools/gen-plays.mjs: Journey stages 1-3 on a desktop (1280 x 800) by the number keys,',
    '# each planned from the rules and played to its results, then Next.', '# viewport 1280x800@1',
    'until 600 Daily Challenge', 'frames 10', 'click =Play', 'until 120 Choose a mode', 'frames 10', 'click =Journey',
    'until 120 Chapter 1', 'frames 10', 'save journey-map', 'click 1. First Supper', 'until 120 Expected length', 'frames 10',
    'save journey-setup', 'click =Start'];
  for (let i = 0; i < 3; i++) {
    const cfg = content.JOURNEY_STAGES[i];
    L.push(...session(cfg, 'key', `journey-${i + 1}`));
    L.push(`save journey-${i + 1}-results`);
    if (i < 2) L.push('click =Next →');
  }
  out('journey-keys', L);
}

// --- the five lessons on a phone by finger ---------------------------------------------------
{
  const L = ['# Generated by tools/gen-plays.mjs: the five Learn lessons on a phone (390 x 844, DPR 3) by finger: each',
    '# lesson step done on the action tray (a refused Feed and Wash, a granted craving, a decoration from the',
    '# drawer), Mote petted by a tap, then the pause sheet and Leave session.', '# viewport 390x844@3',
    'until 600 Daily Challenge', 'frames 10', 'touch =Play', 'until 120 Choose a mode', 'frames 10'];
  for (const [li, lesson] of content.LESSONS.entries()) {
    const cfg = content.getStage(lesson.stageId);
    L.push(`# ${lesson.title}`, 'touch =Learn', 'until 120 Lessons', 'frames 10', `touch ${lesson.title}`, 'until 300 Objective', 'frames 30');
    if (li === 0) L.push('save lesson-1', 'touch =Mote', 'frames 10');
    // simulate the lesson's steps
    const s = new Session(cfg, { mode: 'learn', undo: true, ranked: false, now: 1 });
    if (li === 0) s.act('pet');
    for (const step of lesson.steps) {
      const req = step.require;
      if (req.action === 'decorate') {
        const item = cfg.allowedDecor[0];
        s.act('decorate', { item });
        L.push(...moveLines(cfg, { type: 'decorate', item }, 'touch'));
      } else if (req.action) {
        // play greedily until the action is legal (a full Mote can't eat), then do it
        for (let i = 0; i < 50 && !s.legal.some((a) => a.id === req.action && a.legal); i++) {
          const m = greedy(s.state); s.act(m.type); L.push(...moveLines(cfg, m, 'touch'));
        }
        s.act(req.action);
        L.push(...moveLines(cfg, { type: req.action }, 'touch'));
      } else if (req.invalid) {
        // make the action illegal first (feed / wash until full), then try it once more
        for (let i = 0; i < 20 && s.legal.some((a) => a.id === req.invalid && a.legal); i++) { s.act(req.invalid); L.push(...moveLines(cfg, { type: req.invalid }, 'touch')); }
        s.act(req.invalid);
        L.push(`touch Feed — unavailable`.replace('Feed', LABEL(req.invalid)), 'frames 5');
      } else if (req.craving) {
        // greedy care until a craving shows, then the action that meets it
        let met = false;
        for (let i = 0; i < 200 && !met; i++) {
          const st = s.state;
          if (st.craving) {
            const id = WANT[st.craving.need].find((a) => s.legal.some((x) => x.id === a && x.legal));
            if (id) {
              const r = s.act(id); L.push(...moveLines(cfg, { type: id }, 'touch'));
              met = !!r.cravingBonus;
              continue;
            }
          }
          const m = greedy(st); s.act(m.type); L.push(...moveLines(cfg, m, 'touch'));
        }
        if (!met) throw new Error('no craving met');
      }
    }
    if (s.terminal) {
      // the lesson's last step also met the stage's goal: its results, then Modes
      L.push('until 300 Results', 'expect Session complete', 'frames 10', `save lesson-${li + 1}-done`, 'touch =Modes', 'until 120 Choose a mode', 'frames 10');
      continue;
    }
    L.push('frames 10', 'expect Lesson complete', `save lesson-${li + 1}-done`, 'touch =Pause and menu', 'until 60 Leave session', 'frames 5');
    if (li === 0) L.push('save lesson-pause');
    L.push('touch =Leave session', 'until 120 Choose a mode', 'frames 10');
  }
  out('learn-phone', L);
}

// --- a challenge in short landscape by finger ------------------------------------------------
{
  const cfg = content.challengeConfig('challenge-speed');
  const L = ['# Generated by tools/gen-plays.mjs: the Beat the Clock challenge on a phone held sideways (844 x 390, DPR 3)',
    '# by finger: the setup with the challenge list, the room, the pause sheet with help and back, then the', '# planned session to its results.', '# viewport 844x390@3',
    'until 600 Daily Challenge', 'frames 10', 'touch =Play', 'until 120 Choose a mode', 'frames 10', 'touch =Challenge', 'until 120 Expected length', 'frames 10',
    'touch =Beat the Clock', 'frames 10', 'save challenge-setup', 'touch =Start', 'until 300 Objective', 'frames 30', 'save challenge-room',
    'touch =Pause and menu', 'until 60 Leave session', 'frames 5', 'save challenge-pause', 'touch =Help #2', 'until 60 How to play', 'frames 10',
    'save challenge-help', 'touch =Close', 'frames 10', 'touch =Resume', 'frames 10'];
  const ses = session(cfg, 'touch', 'challenge');
  L.push(...ses.slice(3)); // already in the room
  L.push('save challenge-results');
  out('challenge-land', L);
}
